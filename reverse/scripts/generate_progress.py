"""Generate the compact recovery dashboard, JSON inventory and session-log index.

PROGRESS.md is entirely generated (TASK0078). Historical manual content is
preserved in docs/PROGRESS_ARCHIVE_TASK0078.md. PROGRESS_LOG.md retains its
handwritten sessions; only its contents region is replaced. No ELF access.

    py -3 reverse/scripts/generate_progress.py
    py -3 reverse/scripts/generate_progress.py --check
"""
from __future__ import annotations
import argparse
import datetime
from pathlib import Path
import re
import sys
from recovery_progress import collect, render_compact, encoded, atomic_write, REPORT

ROOT = Path(__file__).resolve().parents[2]
PROGRESS = ROOT / 'docs/PROGRESS.md'
LOG = ROOT / 'docs/PROGRESS_LOG.md'
BEGIN = '<!-- generated:{0}:begin -->'
END = '<!-- generated:{0}:end -->'


def render_log_contents(log_text: str) -> str:
    """A contents list for the log, from its own second-level headings.

    The log is append-at-the-top and already long; without an index a reader has to scroll to
    find out what is in it. GitHub's heading anchors are lowercased, with punctuation dropped and
    spaces turned into hyphens, which is what this reproduces.
    """
    lines = []
    for line in log_text.splitlines():
        if not line.startswith("## ") or line.startswith("## Contents"):
            continue
        title = line[3:].strip()
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        lines.append(f"- [{title}](#{anchor})")
    return "\n".join(lines) or "_No sections yet._"


def splice(text: str, name: str, body: str) -> str:
    begin, end = BEGIN.format(name), END.format(name)
    if begin not in text or end not in text:
        raise SystemExit(f"docs/PROGRESS.md is missing the {name} generated markers")
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    stamp = datetime.date.today().isoformat()
    note = f"<!-- Generated by reverse/scripts/generate_progress.py on {stamp}. Do not edit by hand. -->"
    return f"{head}{begin}\n{note}\n\n{body.rstrip()}\n\n{end}{tail}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail when dashboard, report or log index is stale')
    args = parser.parse_args()
    original = PROGRESS.read_text(encoding='utf-8') if PROGRESS.exists() else ''
    report = collect()
    updated = render_compact(report)
    report_path = ROOT / REPORT
    report_text = encoded(report)
    log_original = LOG.read_text(encoding='utf-8')
    log_updated = splice(log_original, 'contents', render_log_contents(log_original))
    # Date stamps are historical display metadata, not freshness inputs.
    def log_body(text):
        return '\n'.join(line for line in text.splitlines() if not line.startswith('<!-- Generated by'))
    work = [(PROGRESS, original, updated, 'docs/PROGRESS.md', original == updated),
            (LOG, log_original, log_updated, 'docs/PROGRESS_LOG.md contents', log_body(log_original) == log_body(log_updated))]
    stale = [label for _, _, _, label, same in work if not same]
    if not report_path.exists() or report_path.read_text(encoding='utf-8') != report_text:
        stale.append(str(REPORT))
    if args.check:
        if stale:
            print('stale, run `./tools/track_progress.ps1 -Once`: ' + ', '.join(stale), file=sys.stderr)
            return 1
        print('PASS compact progress, report and log index are current')
        return 0
    wrote = []
    for path, before, after, label, same in work:
        if not same:
            atomic_write(path, after, expected=before)
            wrote.append(label)
    if atomic_write(report_path, report_text):
        wrote.append(str(REPORT))
    print('UPDATED ' + ', '.join(wrote) if wrote else 'PASS compact progress already current')
    return 0


if __name__ == '__main__':
    from track_progress import writer_lock
    with writer_lock():
        raise SystemExit(main())
