EasterEggs easterEggs;

EasterEggs::EasterEggs(GameInputRouter* router) noexcept
    : input(router),records(authoredCodes.data()),recordCount(authoredCodes.size()) {}

GameInputResult EasterEggs::Activate()
{
    if (!input || !input->registrations || input->count>input->capacity)
        return GAME_INPUT_INVALID_BINDING;
    if (registrationsAttached) return input->result=GAME_INPUT_OK;
    // Native host-storage failures are explicit and leave the source owner
    // unchanged. In the valid source domain all sixteen registrations exist.
    if (input->capacity-input->count<16 ||
        std::numeric_limits<std::uint64_t>::max()-input->nextOrder<16)
        return input->result=GAME_INPUT_CAPACITY;
    GameInputTarget target{};
    target.kind=GAME_INPUT_EASTER_EGGS;
    target.owner.easterEggs=this;
    for (std::int32_t event=0x85;event<=0x94;++event) {
        const auto result=gameInputRegister(input,0,event,target);
        if (result!=GAME_INPUT_OK)return result;
    }
    pendingMessage=0;
    lastMessage=0;
    active=1;
    registrationsAttached=true;
    ClearButtons();
    return GAME_INPUT_OK;
}

GameInputResult EasterEggs::UnActivate()
{
    if (!input)return GAME_INPUT_INVALID_BINDING;
    if (registrationsAttached) {
        for (std::int32_t event=0x85;event<=0x94;++event)
            gameInputUnregister(input,0,event);
        registrationsAttached=false;
    }
    active=0;
    pendingMessage=0;
    lastMessage=0;
    ClearButtons();
    return GAME_INPUT_OK;
}

void EasterEggs::JoyHandler(std::int32_t device,std::int32_t event,std::uint8_t value)
{
    (void)device;
    (void)value; // The final handler stores every incoming event, regardless of value.
    if (!active)return;
    if (buttonCount>=8) {
        ClearButtons();
        return;
    }
    const auto position=(ringStart+buttonCount)&7u;
    ++buttonCount;
    buttons[position]=static_cast<std::uint32_t>(event);
    if (buttonCount!=8)return;
    for (std::size_t index=0;index<recordCount;++index) {
        auto& code=records[index];
        bool matches=true;
        for (std::size_t button=0;button<8;++button) {
            if (code.buttons[button]!=buttons[(ringStart+button)&7u]) {
                matches=false;
                break;
            }
        }
        if (!matches)continue;
        (void)UnlockRecord(index);
        return;
    }
    --buttonCount;
    ringStart=(ringStart+1)&7u;
}

bool EasterEggs::UnlockRecord(std::size_t index) noexcept
{
    if(index>=recordCount || !records)return false;
    auto& code=records[index];
    // Final 24F9F8: only an authored match may mutate other records.
    if(code.exclusiveGroup) {
        for(std::size_t other=0;other<recordCount;++other)
            if(records[other].exclusiveGroup==code.exclusiveGroup)
                records[other].unlocked=0;
    }
    code.unlocked=1;
    pendingMessage=1;
    lastMessage=code.languageMessageId;
    ClearButtons();
    return true;
}

bool EasterEggs::TryUnlockTextCode(const char* text,std::size_t length) noexcept
{
    // Text entry is an explicitly PC-only transport into PAL 24F9F8. It
    // never supplies an invented graphic effect or changes an original
    // unlock's persistent/exclusive-group fields.
    if(!active || !records || !text || length!=6)return false;
    const auto upper=[](char c) noexcept -> char {
        return c>='a' && c<='z' ? static_cast<char>(c-'a'+'A') : c;
    };
    if(upper(text[0])!='H'||upper(text[1])!='P'||text[2]!='2'||
       upper(text[3])!='C'||text[4]<'0'||text[4]>'9'||
       text[5]<'0'||text[5]>'9')return false;
    const std::size_t number=static_cast<std::size_t>(text[4]-'0')*10+
                              static_cast<std::size_t>(text[5]-'0');
    if(number==0 || number>recordCount)return false;
    // The PAL record with eight zero inputs is not a manually enterable
    // code. Do not create a new unlock path for a code without buttons.
    const auto& record=records[number-1];
    bool hasButton=false;
    for(const auto button:record.buttons)hasButton|=button!=0;
    return hasButton && UnlockRecord(number-1);
}

void EasterEggs::ClearButtons() noexcept
{
    buttonCount=0;
}

std::uint32_t EasterEggs::IsTrackUnlocked(std::uint32_t track,bool reverse) const noexcept
{
    return IsEasterEggUnlocked(reverse?4u:3u,track);
}

std::uint32_t EasterEggs::IsCarUnlocked(std::uint32_t model,bool pursuit) const noexcept
{
    // Final PAL24F8F8 uses kind2/1; beta's kind1/0 is not port authority.
    return IsEasterEggUnlocked(pursuit?2u:1u,model);
}

std::uint32_t EasterEggs::IsEasterEggUnlocked(std::uint32_t kind,std::uint32_t selector) const noexcept
{
    for (std::size_t index=0;index<recordCount;++index) {
        const auto& code=records[index];
        if (code.kind==kind && code.selector==selector)return code.unlocked;
    }
    return 0;
}

