void EasterEggs::ResetNonPersistentUnlocks() noexcept
{
    // Final24F700..24F744: the branch-likely executes its store only
    // when the same record's persistent lane is zero.
    for(std::size_t index=0;index<recordCount;++index)
        if(!records[index].persistent)records[index].unlocked=0;
}
